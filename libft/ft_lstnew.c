#include "libft.h"

t_list	*ft_lstnew(void *content)
{
	t_list	*ll;

	ll = malloc(sizeof(t_list));
	if (!ll)
		return (NULL);
	ll->content = content;
	ll->next = NULL;
	return (ll);
}
