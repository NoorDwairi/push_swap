#include "libft.h"

t_list	*ft_lstmap(t_list *lst, void *(*f)(void *), void (*del)(void *))
{
	t_list	*new_list;
	t_list	*p;
	void	*new_content;
	t_list	*new_node;

	p = lst;
	new_list = NULL;
	while (p != NULL)
	{
		new_content = f(p->content);
		new_node = ft_lstnew(new_content);
		if (!new_node)
		{
			del(new_content);
			ft_lstclear(&new_list, del);
			return (NULL);
		}
		ft_lstadd_back(&new_list, new_node);
		p = p->next;
	}
	return (new_list);
}
