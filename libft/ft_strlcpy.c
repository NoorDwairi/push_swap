#include "libft.h"

size_t	ft_strlcpy(char *dst, const char *src, size_t size)
{
	size_t	i;
	size_t	sz;

	i = 0;
	sz = ft_strlen(src);
	if (size == 0)
		return (sz);
	while (i < size - 1)
	{
		if (src[i] == '\0')
			break ;
		dst[i] = src[i];
		i++;
	}
	dst[i] = '\0';
	return (sz);
}
